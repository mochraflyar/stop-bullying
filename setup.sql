-- ============================================================
--  STOP BULLYING — Setup database (Supabase SQL Editor)
--  Jalankan seluruh blok ini satu kali di dashboard Supabase.
--  Aman dijalankan ulang (idempotent).
--
--  URUTAN PENTING: revoke -> RLS + policy -> grant minimal
--  Jangan pernah "grant all ... to anon" (jebakan paling umum).
-- ============================================================

-- ---------- 1. Tabel laporan ----------
create table if not exists public.laporan (
  id         bigint generated by default as identity primary key,
  dibuat_at  timestamptz not null default now(),
  anonim     boolean not null default true,
  nama       text,
  kelas      text,
  bentuk     text,
  isi        text   not null,
  status     text   not null default 'baru'
);

-- ---------- 2. Index untuk query dashboard ----------
create index if not exists laporan_terbaru_idx
  on public.laporan (dibuat_at desc);

-- ---------- 3. Buang grant otomatis (bila ada) ----------
--  Dua kondisi mungkin terjadi pada project Anda:
--  a) Project LAMA  -> tabel otomatis dapat GRANT penuh ke anon/authenticated
--  b) Project BARU  -> tabel TIDAK lagi dapat GRANT otomatis
--     (perubahan Supabase 30 Oktober 2026)
--
--  Revoke di sini membuat hasil akhir sama untuk kedua kondisi.
--  WAJIB revoke dulu, baru grant — grant tidak pernah mencabut hak yang sudah ada.
revoke all on table public.laporan from public, anon, authenticated;

-- ---------- 4. Kunci baris (Row Level Security) ----------
alter table public.laporan enable row level security;

-- Pelapor (peran "anon", tanpa login):
-- hanya boleh MENAMBAHKAN laporan, tidak bisa membaca/mengubah/hapus.
drop policy if exists "pelapor insert laporan" on public.laporan;
create policy "pelapor insert laporan" on public.laporan
  for insert to anon with check (true);

-- Guru (peran "authenticated", sudah login lewat dashboard):
-- boleh membaca, mengubah status, dan menghapus laporan.
drop policy if exists "guru read laporan" on public.laporan;
create policy "guru read laporan" on public.laporan
  for select to authenticated using (true);

drop policy if exists "guru update laporan" on public.laporan;
create policy "guru update laporan" on public.laporan
  for update to authenticated using (true);

drop policy if exists "guru delete laporan" on public.laporan;
create policy "guru delete laporan" on public.laporan
  for delete to authenticated using (true);

-- ---------- 5. GRANT — izin akses tabel ----------
--  GRANT menentukan apakah role boleh menyentuh tabel sama sekali.
--  RLS menentukan baris mana yang boleh dilihat, SETELAH role punya izin.
--  Tanpa GRANT, PostgREST membalas 42501 sebelum RLS sempat dicek.

-- Pelapor: HANYA boleh menambah laporan (tidak bisa membaca laporan siapa pun)
grant insert on table public.laporan to anon;

--  PENTING: tabel ini adalah "write-only" untuk peran anon.
--  PostgreSQL mensyaratkan hak SELECT untuk menjalankan
--  "INSERT ... RETURNING". Frontend memakai header
--  "Prefer: return=minimal" sehingga PostgREST MENGAKALI klausa RETURNING
--  dan tidak butuh hak SELECT. Karena itu hak SELECT TIDAK diberikan
--  ke anon — inilah yang membuat semua laporan tetap tidak bisa dibaca
--  siapa pun yang punya anon key.
--
--  Jangan "memperbaiki" ini dengan memberi SELECT ke anon.
--  Kalau RLS nanti dimatikan, seluruh laporan jadi bisa dibaca publik.

-- Guru: membaca, mengubah status, menghapus
grant select, update, delete on table public.laporan to authenticated;

-- Internal Supabase / tooling admin (bypass RLS).
-- Kunci service_role TIDAK PERNAH ditaruh di file frontend.
grant all on table public.laporan to service_role;

-- ---------- 6. GRANT sequence identity ----------
--  Kolom id memakai "generated by default as identity", jadi ada sequence
--  terpisah. Tanpa hak USAGE, INSERT akan gagal dengan:
--  "permission denied for sequence laporan_..._seq"
do $$
declare
  seq text;
begin
  for seq in
    select c.relname
      from pg_class c
      join pg_depend d on d.objid = c.oid
      join pg_class t on t.oid = d.refobjid
     where d.classid  = 'pg_class'::regclass
       and d.refclassid = 'pg_class'::regclass
       and c.relkind = 'S'
       and t.relname = 'laporan'
  loop
    execute format(
      'grant usage, select on sequence public.%I to anon, authenticated, service_role',
      seq
    );
  end loop;
end $$;

-- ---------- 7. Jaminan: laporan non-anonim selalu punya nama ----------
do $$
begin
  alter table public.laporan
    add constraint laporan_nama_wajib check (anonim = true or nama is not null);
exception
  when duplicate_object then null;
end $$;

-- ---------- 8. Lindungi tabel yang dibuat di kemudian hari ----------
--  Berlaku mulai 30 Oktober 2026 untuk semua project, tapi bisa dijalankan
--  sekarang juga. Tabel baru di schema public otomatis minta GRANT eksplisit.
alter default privileges for role postgres in schema public
  revoke select, insert, update, delete on tables from anon, authenticated, service_role;

alter default privileges for role postgres in schema public
  revoke usage, select on sequences from anon, authenticated, service_role;

-- ============================================================
--  VERIFIKASI — jalankan query ini, lalu periksa hasilnya
-- ============================================================

-- (1) RLS harus aktif  ->  relrowsecurity = t
select relname, relrowsecurity
  from pg_class where relname = 'laporan';

-- (2) Policy harus 4 buah:
--     pelapor insert laporan  (to anon)
--     guru read / update / delete  (to authenticated)
select policyname, roles, cmd
  from pg_policies where tablename = 'laporan' order by policyname;

-- (3) Grant yang berlaku:
--     anon         -> hanya INSERT
--     authenticated-> SELECT, UPDATE, DELETE
select grantee, privilege_type
  from information_schema.role_table_grants
 where table_name = 'laporan'
   and grantee in ('anon','authenticated','service_role')
 order by grantee, privilege_type;

-- (4) Sequence identity harus punya hak USAGE untuk anon.
--     (information_schema tidak mengekspos sequence_name, jadi pakai aclexplode)
select c.relname as sequence, g.rolname as grantee, a.privilege_type
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  cross join lateral aclexplode(c.relacl) a
  join pg_roles g on g.oid = a.grantee
 where n.nspname = 'public'
   and c.relkind = 'S'
   and c.relname like 'laporan%'
 order by g.rolname;

-- (5) Pemeriksaan keamanan: daftar tabel di schema public yang
--     masih bisa dibaca anybody yang punya anon key (RLS OFF).
--     Hasil HARUS kosong.
select c.relname
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = 'public'
   and c.relkind = 'r'
   and not c.relrowsecurity
   and has_table_privilege('anon', c.oid, 'SELECT');
